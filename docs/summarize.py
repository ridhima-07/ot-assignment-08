def f(x, d=3):
    if x is None: return "–"
    if isinstance(x, (list, tuple)) and len(x) == 2 and all(isinstance(v, (int, float)) for v in x): return f"{x[0]:.{d}g} ± {x[1]:.2g}"
    if isinstance(x, float): return f"{x:.{d}g}"
    return str(x)

